export function paintIcon(element, name = element.dataset.icon) {
  const rows = glyphs[name];
  if (!rows) return;
  let canvas = element.querySelector(':scope > .pixel-icon');
  if (!canvas) {
    canvas = document.createElement('canvas');
    canvas.width = canvas.height = 10;
    canvas.className = 'pixel-icon';
    canvas.setAttribute('aria-hidden', 'true');
    element.prepend(canvas);
  }
  const context = canvas.getContext('2d');
  context.clearRect(0, 0, 10, 10);
  rows.forEach((row, y) => Array.from(row).forEach((pixel, x) => {
    if (pixel === '.') return;
    context.fillStyle = pixel === '#' ? '#f8d88c' : '#b67c45';
    context.fillRect(x, y, 1, 1);
  }));
}
